"""Generate db/migrations/100_ts_generated.sql: one ts.<table> per template sheet.

The template specs (templates/spec/*.toml) are the single source of truth, so the input
tables are generated, never hand-written. Run after any spec change:
    ./atlas templates            (also regenerates the workbooks)
    python templates/ddl.py --check   exits 1 if the committed SQL is out of date

Conventions (docs/dev/contracts.md section 3.2):
  - every table gets batch_id and row_num;
  - columns that name a substation or plant get a resolved <col>_code column, filled by
    the loader through config/aliases.csv;
  - vector sheets get geom geometry(Geometry, 4326);
  - question sheets all load into ts.qa_answer.
Migrations numbered 1xx are rebuildable: when this file changes, the migration runner drops
schema ts and re-creates it, and the data is reloaded from data/ (inputs are never edited in
the database).
"""
from __future__ import annotations

import hashlib
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = ROOT / "templates" / "spec"
OUT = ROOT / "db" / "migrations" / "100_ts_generated.sql"

PG_TYPE = {
    "text": "text",
    "int": "integer",
    "number": "double precision",
    "month": "date",
    "date": "date",
    "datetime": "timestamptz",
    "yn": "boolean",
    "enum": "text",
}

# Columns whose values are names to be resolved to canonical codes (loaders/names.py).
RESOLVE_SUBSTATION = {
    "substation", "from_substation", "to_substation", "connection_substation",
    "bulk_supply_point", "planned_supply_point", "substation_or_area",
    "from_ss", "to_ss", "ss_code",
}
RESOLVE_PLANT = {"plant"}


def resolvable(column: str) -> str | None:
    if column in RESOLVE_SUBSTATION:
        return "substation"
    if column in RESOLVE_PLANT:
        return "plant"
    return None


def load_specs() -> list[tuple[Path, dict]]:
    return [(p, tomllib.loads(p.read_text(encoding="utf-8"))) for p in sorted(SPEC_DIR.glob("T*.toml"))]


def render(specs: list[tuple[Path, dict]]) -> str:
    digest = hashlib.sha256()
    for p, _ in specs:
        digest.update(p.name.encode())
        digest.update(p.read_bytes())
    lines = [
        "-- GENERATED by templates/ddl.py from templates/spec/*.toml. Do not edit by hand.",
        f"-- spec digest: {digest.hexdigest()[:16]}",
        "CREATE SCHEMA IF NOT EXISTS ts;",
        "",
        "CREATE TABLE IF NOT EXISTS ts.qa_answer (",
        "    batch_id bigint NOT NULL,",
        "    row_num integer NOT NULL,",
        "    template text NOT NULL,",
        "    sheet text NOT NULL,",
        "    question_id text NOT NULL,",
        "    question text,",
        "    answer text",
        ");",
        "CREATE INDEX IF NOT EXISTS qa_answer_batch_idx ON ts.qa_answer (batch_id);",
        "",
    ]
    for path, spec in specs:
        for sheet in spec["sheets"]:
            if sheet.get("format") == "qa":
                continue
            table = sheet["table"]
            cols = ["    batch_id bigint NOT NULL", "    row_num integer NOT NULL"]
            for col in sheet["columns"]:
                cols.append(f"    \"{col['name']}\" {PG_TYPE[col['type']]}")
                if resolvable(col["name"]) and col["name"] != "ss_code":
                    cols.append(f"    \"{col['name']}_code\" text")
            if sheet.get("format") == "vector":
                cols.append("    geom geometry(Geometry, 4326)")
            lines.append(f"-- {spec['id']} {sheet['name']}: {sheet.get('grain', '')}")
            lines.append(f"CREATE TABLE IF NOT EXISTS ts.{table} (")
            lines.append(",\n".join(cols))
            lines.append(");")
            lines.append(f"CREATE INDEX IF NOT EXISTS {table}_batch_idx ON ts.{table} (batch_id);")
            key = sheet.get("key", [])
            if key:
                lines.append(f"CREATE INDEX IF NOT EXISTS {table}_key_idx ON ts.{table} ({', '.join(chr(34) + k + chr(34) for k in key)});")
            if sheet.get("format") == "vector":
                lines.append(f"CREATE INDEX IF NOT EXISTS {table}_geom_idx ON ts.{table} USING gist (geom);")
            lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    sql = render(load_specs())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != sql:
            print(f"{OUT.relative_to(ROOT)} is out of date: run ./atlas templates")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
