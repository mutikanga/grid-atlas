"""Write synthetic files exactly in the template formats, plus their manifests.

- Workbooks: one xlsx per template, sheet names and column order from the spec,
  row 1 = column names, data from row 2, a README sheet first, and the workbook
  keyword 'gridatlas-synthetic'. File name SYNTHETIC_<id>_<slug>.xlsx.
- CSV and vector files carry the SYNTHETIC_ prefix in the file name.
- Values are written in the contract's text forms: months 'YYYY-MM', dates
  'YYYY-MM-DD', date-times 'YYYY-MM-DD HH:MM' (EAT), yes/no 'Y'/'N'.
- Output is byte-for-byte repeatable for a given seed: zip timestamps and document
  dates inside the xlsx are fixed, so the manifest hashes do not change between runs.
"""
from __future__ import annotations

import hashlib
import io
import json
import math
import tomllib
import zipfile
from dataclasses import dataclass, field
from datetime import date, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from openpyxl import Workbook

ROOT = Path(__file__).resolve().parents[2]
SPEC_DIR = ROOT / "templates" / "spec"
KEYWORD = "gridatlas-synthetic"
FIXED_TIME = datetime(2026, 11, 1, 0, 0, 0)
BANNER = "SYNTHETIC DATA - NOT UETCL DATA. Generated by engine/synthetic for testing the Grid Atlas."


def load_specs(spec_dir: Path = SPEC_DIR) -> dict[str, dict]:
    """Every template spec, keyed by its slug (which equals its dataset)."""
    specs = {}
    for path in sorted(spec_dir.glob("T*.toml")):
        with path.open("rb") as fh:
            spec = tomllib.load(fh)
        specs[spec["slug"]] = spec
    return specs


def sheet_spec(spec: dict, name: str) -> dict:
    """The spec entry of one sheet, by sheet name."""
    for sh in spec["sheets"]:
        if sh["name"] == name:
            return sh
    raise KeyError(f"{spec['id']} has no sheet {name!r}")


def column_names(sheet: dict) -> list[str]:
    """Column names of a sheet in spec order (qa sheets: question_id, question, answer)."""
    if sheet.get("format") == "qa":
        return ["question_id", "question", "answer"]
    return [c["name"] for c in sheet["columns"]]


# --------------------------------------------------------------------------- value formatting
def _is_blank(v) -> bool:
    return v is None or (isinstance(v, float) and math.isnan(v)) or (v is pd.NaT)


def format_value(v, col_type: str):
    """Convert a Python/pandas value to what the cell (or CSV field) should hold for this type."""
    if _is_blank(v) or (isinstance(v, str) and v == "" and col_type != "text"):
        return None
    if col_type == "month":
        if isinstance(v, (datetime, date, pd.Timestamp)):
            return v.strftime("%Y-%m")
        return str(v)
    if col_type == "date":
        if isinstance(v, (datetime, date, pd.Timestamp)):
            return v.strftime("%Y-%m-%d")
        return str(v)
    if col_type == "datetime":
        if isinstance(v, (datetime, pd.Timestamp)):
            return v.strftime("%Y-%m-%d %H:%M")
        return str(v)
    if col_type == "yn":
        if isinstance(v, (bool, np.bool_)):
            return "Y" if v else "N"
        return str(v)
    if col_type == "int":
        if isinstance(v, str):
            return v  # deliberately bad values (dirty variant) pass through unchanged
        return int(v)
    if col_type == "number":
        if isinstance(v, str):
            return v
        return float(round(float(v), 4))
    return str(v) if not isinstance(v, str) else v


def frame_for_sheet(sheet: dict, df: pd.DataFrame) -> pd.DataFrame:
    """Order and type a DataFrame's columns like the spec; missing columns become blank."""
    cols = column_names(sheet)
    types = {c["name"]: c["type"] for c in sheet.get("columns", [])}
    out = pd.DataFrame(index=range(len(df)))
    for c in cols:
        src = df[c].tolist() if c in df.columns else [None] * len(df)
        out[c] = [format_value(v, types.get(c, "text")) for v in src]
    return out


# --------------------------------------------------------------------------- xlsx
def _normalise_zip(data: bytes) -> bytes:
    """Rewrite an xlsx (a zip) with fixed entry timestamps so identical content gives identical bytes."""
    src = zipfile.ZipFile(io.BytesIO(data))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            raw = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                raw = _fix_core_dates(raw)
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 11, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            dst.writestr(zi, raw)
    return buf.getvalue()


def _fix_core_dates(raw: bytes) -> bytes:
    """Replace the created/modified stamps in docProps/core.xml with FIXED_TIME."""
    import re

    text = raw.decode("utf-8")
    stamp = FIXED_TIME.strftime("%Y-%m-%dT%H:%M:%SZ")
    text = re.sub(r"(<dcterms:created[^>]*>)[^<]*(</dcterms:created>)", rf"\g<1>{stamp}\g<2>", text)
    text = re.sub(r"(<dcterms:modified[^>]*>)[^<]*(</dcterms:modified>)", rf"\g<1>{stamp}\g<2>", text)
    return text.encode("utf-8")


def write_workbook(path: Path, spec: dict, sheets: dict[str, pd.DataFrame], qa_answers: dict[str, dict] | None = None) -> None:
    """Write one template workbook.

    sheets maps sheet name -> DataFrame for the xlsx sheets to fill. qa sheets are filled
    from the spec's questions plus qa_answers[sheet][question_id]. csv and vector sheets
    are not written into the workbook: their data travels in separate files.
    """
    qa_answers = qa_answers or {}
    wb = Workbook()
    readme = wb.active
    readme.title = "README"
    readme.append([BANNER])
    readme.append([f"Template {spec['id']} {spec['slug']}: {spec['title']}"])
    readme.append(["Every value in this workbook is invented. Do not quote any figure from it."])
    for sh in spec["sheets"]:
        fmt = sh.get("format", "xlsx")
        if fmt in ("csv", "vector"):
            continue
        ws = wb.create_sheet(sh["name"])
        cols = column_names(sh)
        ws.append(cols)
        if fmt == "qa":
            answers = qa_answers.get(sh["name"], {})
            for q in sh["questions"]:
                ws.append([q["id"], q["text"], answers.get(q["id"], "Synthetic test answer: not applicable.")])
            continue
        df = sheets.get(sh["name"])
        if df is None:
            continue
        typed = frame_for_sheet(sh, df)
        for row in typed.itertuples(index=False):
            ws.append([None if _is_blank(v) else v for v in row])
    props = wb.properties
    props.keywords = KEYWORD
    props.title = f"SYNTHETIC {spec['id']} {spec['slug']}"
    props.creator = "engine/synthetic"
    props.description = BANNER
    props.created = FIXED_TIME
    props.modified = FIXED_TIME
    props.lastModifiedBy = "engine/synthetic"
    buf = io.BytesIO()
    wb.save(buf)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(_normalise_zip(buf.getvalue()))


# --------------------------------------------------------------------------- csv and geojson
def write_csv(path: Path, sheet: dict, df: pd.DataFrame) -> None:
    """Write a csv-format sheet with the spec's columns, '\\n' line ends and no index."""
    typed = frame_for_sheet(sheet, df)
    path.parent.mkdir(parents=True, exist_ok=True)
    typed.to_csv(path, index=False, lineterminator="\n")


def _round_coords(coords, nd: int = 6):
    if isinstance(coords, (list, tuple)) and coords and isinstance(coords[0], (int, float)):
        return [round(float(c), nd) for c in coords]
    return [_round_coords(c, nd) for c in coords]


def write_geojson(path: Path, features: list[dict], name: str, columns: list[str] | None = None,
                  types: dict[str, str] | None = None) -> None:
    """Write a GeoJSON FeatureCollection in EPSG:4326 (lon, lat order).

    features: dicts with 'geometry' ({'type', 'coordinates'}) and 'properties'.
    If columns is given, properties are restricted to and ordered by it.
    """
    types = types or {}
    out = []
    for f in features:
        props = f["properties"]
        if columns is not None:
            props = {c: format_value(props.get(c), types.get(c, "text")) for c in columns}
        out.append({"type": "Feature", "properties": props,
                    "geometry": {"type": f["geometry"]["type"], "coordinates": _round_coords(f["geometry"]["coordinates"])}})
    fc = {"type": "FeatureCollection", "name": name,
          "crs": {"type": "name", "properties": {"name": "urn:ogc:def:crs:OGC:1.3:CRS84"}},
          "synthetic": True, "features": out}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(fc, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- manifest
def sha256_of(path: Path) -> str:
    """sha256 hex digest of a file."""
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


@dataclass
class ManifestFile:
    """One [[files]] entry of a manifest."""

    path: str
    sheet: str | None = None
    layer: str | None = None
    name_field: str | None = None


@dataclass
class Manifest:
    """A dataset folder's manifest.toml (docs/dev/contracts.md section 8)."""

    dataset: str
    template: str
    files: list[ManifestFile] = field(default_factory=list)
    provenance: str = "synthetic"
    received_from: str = "engine/synthetic"
    received_on: date = date(2026, 11, 1)
    adapter: str = "template"
    notes: str = ""


def _toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def write_manifest(folder: Path, m: Manifest) -> Path:
    """Write manifest.toml for a dataset folder, hashing each listed file."""
    lines = [
        "# SYNTHETIC: generated by engine/synthetic. Not UETCL data.",
        f"dataset = {_toml_str(m.dataset)}",
        f"template = {_toml_str(m.template)}",
        f"provenance = {_toml_str(m.provenance)}",
        f"received_from = {_toml_str(m.received_from)}",
        f"received_on = {m.received_on.isoformat()}",
        f"adapter = {_toml_str(m.adapter)}",
    ]
    if m.notes:
        lines.append(f"notes = {_toml_str(m.notes)}")
    for f in m.files:
        lines.append("")
        lines.append("[[files]]")
        lines.append(f"path = {_toml_str(f.path)}")
        if f.sheet:
            lines.append(f"sheet = {_toml_str(f.sheet)}")
        if f.layer:
            lines.append(f"layer = {_toml_str(f.layer)}")
        if f.name_field:
            lines.append(f"name_field = {_toml_str(f.name_field)}")
        lines.append(f"sha256 = {_toml_str(sha256_of(folder / f.path))}")
    path = folder / "manifest.toml"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
